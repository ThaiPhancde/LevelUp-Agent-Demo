import pytest

from app.core import registry as r


@pytest.mark.parametrize(
    ('tool', 'expected'),
    [
        ('meta_ads.create_draft', 'WRITE_DRAFT'),
        ('crm.reply_draft', 'WRITE_DRAFT'),
        ('crm.ticket_note', 'WRITE_DRAFT'),
        ('meta_ads.publish', 'WRITE_EXTERNAL'),
        ('payment.charge', 'WRITE_EXTERNAL'),
        ('messaging.send', 'WRITE_EXTERNAL'),
        ('mock.market', 'READ'),
        ('engine.qa', 'READ'),
        ('workflow.plan', 'READ'),
        ('unknown.tool', 'WRITE_EXTERNAL'),
    ],
    ids=[
        'tool_meta_ads_create_draft',
        'tool_crm_reply_draft',
        'tool_crm_ticket_note',
        'tool_meta_ads_publish',
        'tool_payment_charge',
        'tool_messaging_send',
        'tool_mock_market',
        'tool_engine_qa',
        'tool_workflow_plan',
        'tool_unknown',
    ],
)
def test_required_permission(tool, expected):
    assert r.required_permission(tool) == expected


